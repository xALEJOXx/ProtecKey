-- Tabla de analisis individuales
CREATE TABLE IF NOT EXISTS analisis (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    prediction INTEGER NOT NULL,
    classification VARCHAR(100) NOT NULL,
    real_label INTEGER,
    evaluation VARCHAR(10),

    CONSTRAINT chk_prediction
        CHECK (prediction IN (0, 1)),

    CONSTRAINT chk_real_label
        CHECK (real_label IN (0, 1)),

    CONSTRAINT chk_evaluation
        CHECK (evaluation IN ('TP', 'TN', 'FP', 'FN'))
);

-- Tabla de analisis por lotes
CREATE TABLE IF NOT EXISTS analisis_lotes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    nombre_archivo VARCHAR(255) NOT NULL,
    total_registros INTEGER NOT NULL,
    normales INTEGER NOT NULL,
    maliciosos INTEGER NOT NULL,
    porcentaje_malicioso DOUBLE PRECISION,
    tiene_etiquetas BOOLEAN DEFAULT FALSE,
    tn INTEGER,
    fp INTEGER,
    fn INTEGER,
    tp INTEGER,
    accuracy DOUBLE PRECISION,
    precision_score DOUBLE PRECISION,
    recall DOUBLE PRECISION,
    f1 DOUBLE PRECISION,
    fpr DOUBLE PRECISION,
    fnr DOUBLE PRECISION
);
